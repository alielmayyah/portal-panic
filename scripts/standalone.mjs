import { readdir, readFile, writeFile } from 'node:fs/promises';

const dist = new URL('../dist/', import.meta.url);
const html = await readFile(new URL('index.html', dist), 'utf8');
const scriptTag = /<script\b[^>]*\bsrc="(?:\.?\/)?(assets\/[^"?#]+)"[^>]*><\/script>/;
const styleTag = /<link\b[^>]*\bhref="(?:\.?\/)?(assets\/[^"?#]+\.css)"[^>]*>/;
if (!scriptTag.test(html) || !styleTag.test(html)) throw new Error('Could not locate the standalone game assets.');

// Only one script and one stylesheet are inlined, so anything else the build emits
// (extra chunks, preloads, large images or fonts) would be missing from the offline file.
const scriptCount = (html.match(/<script\b[^>]*\bsrc=/gi) || []).length;
const styleCount = (html.match(/<link\b[^>]*\brel=["']?(?:stylesheet|modulepreload)\b/gi) || []).length;
if (scriptCount !== 1 || styleCount !== 1) {
  throw new Error(`Standalone build expects one script and one stylesheet, found ${scriptCount} and ${styleCount}.`);
}

const scriptPath = html.match(scriptTag)[1];
const stylePath = html.match(styleTag)[1];
const inlined = new Set([scriptPath, stylePath].map((p) => p.replace(/^assets\//, '')));
const extra = (await readdir(new URL('assets/', dist))).filter((f) => !inlined.has(f) && !f.endsWith('.map'));
if (extra.length) throw new Error(`Standalone build cannot inline: ${extra.join(', ')}. portal-panic.html would not work offline.`);

const script = await readFile(new URL(scriptPath, dist), 'utf8');
const style = await readFile(new URL(stylePath, dist), 'utf8');
const standalone = html
  .replace(scriptTag, () => '<script type="module">' + script.replace(/<\/script/gi, '<\\/script') + '</script>')
  .replace(styleTag, () => '<style>' + style.replace(/<\/style/gi, '<\\/style') + '</style>');
await writeFile(new URL('../portal-panic.html', import.meta.url), '<!-- Generated by npm run build. Edit index.html and src/ instead. -->\n' + standalone);
