// Builds portal-panic.html: dist/index.html with its one JS module and one stylesheet inlined,
// so the game runs offline from a double-click (file://). Run after `vite build`.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { parseAst } from 'vite';

const dist = new URL('../dist/', import.meta.url);
const out = new URL('../portal-panic.html', import.meta.url);
const BANNER = '<!-- Generated by npm run build. Edit index.html and src/ instead. -->\n';

const fail = (msg) => {
  throw new Error(`standalone: ${msg} portal-panic.html would not work offline.`);
};

const html = await readFile(new URL('index.html', dist), 'utf8');

// Attribute values may be quoted either way and in any order; Vite emits e.g.
// <script type="module" crossorigin src="./assets/index-abc.js"></script> in <head>.
const attr = (tag, name) => {
  const m = tag.match(new RegExp(`\\s${name}\\s*=\\s*(?:"([^"]*)"|'([^']*)'|([^\\s"'>]+))`, 'i'));
  return m ? (m[1] ?? m[2] ?? m[3]) : null;
};
const hasAttr = (tag, name) => new RegExp(`\\s${name}(?=[\\s=>/])`, 'i').test(tag);
// Map a build URL (./assets/x.js, /assets/x.js, /base/assets/x.js) to its path inside dist/.
const localPath = (url) => {
  if (!url || /^(?:[a-z][a-z0-9+.-]*:)?\/\//i.test(url) || /^data:/i.test(url)) return null;
  const clean = url.split(/[?#]/)[0];
  const i = clean.indexOf('assets/');
  return i === -1 ? clean.replace(/^\.?\//, '') : clean.slice(i);
};

const scriptTags = [...html.matchAll(/<script\b[^>]*>\s*<\/script\s*>/gi)].filter((m) => hasAttr(m[0], 'src'));
const linkTags = [...html.matchAll(/<link\b[^>]*>/gi)];
const styleTags = linkTags.filter((m) => /\bstylesheet\b/i.test(attr(m[0], 'rel') ?? ''));
const preloads = linkTags.filter((m) => /\b(?:modulepreload|preload|prefetch)\b/i.test(attr(m[0], 'rel') ?? ''));

if (scriptTags.length !== 1 || styleTags.length !== 1) {
  fail(`expected one external script and one stylesheet in dist/index.html, found ${scriptTags.length} and ${styleTags.length}.`);
}
if (preloads.length) fail(`extra chunks are preloaded (${preloads.map((m) => attr(m[0], 'href')).join(', ')}); keep the build in a single chunk.`);

const scriptTag = scriptTags[0][0];
const styleTag = styleTags[0][0];
if ((attr(scriptTag, 'type') ?? '').toLowerCase() !== 'module') fail(`the entry script is not type="module": ${scriptTag}`);
const scriptPath = localPath(attr(scriptTag, 'src'));
const stylePath = localPath(attr(styleTag, 'href'));
if (!scriptPath || !stylePath) fail('the entry script or stylesheet is not a local build file.');

// Every other local file the page references (icons, manifests, images) would be missing offline.
for (const m of html.matchAll(/<(?:link|img|source|video|audio|script)\b[^>]*>/gi)) {
  const p = localPath(attr(m[0], 'href') ?? attr(m[0], 'src'));
  if (p && p !== scriptPath && p !== stylePath) fail(`dist/index.html references ${p}, which cannot be inlined.`);
}

// Anything else the build emitted (extra chunks, fonts, images, wasm, workers, public/ files)
// is not part of the standalone file, so refuse rather than ship a broken copy.
const walk = async (dir, prefix = '') =>
  (await Promise.all((await readdir(dir, { withFileTypes: true })).map((e) =>
    e.isDirectory() ? walk(new URL(`${e.name}/`, dir), `${prefix}${e.name}/`) : [`${prefix}${e.name}`],
  ))).flat();
const allowed = new Set(['index.html', scriptPath, stylePath]);
const extra = (await walk(dist)).filter((f) => !allowed.has(f) && !f.endsWith('.map'));
if (extra.length) fail(`the build emitted files that cannot be inlined: ${extra.join(', ')}.`);

const script = await readFile(new URL(scriptPath, dist), 'utf8');
const style = await readFile(new URL(stylePath, dist), 'utf8');

const cssUrls = [...style.matchAll(/url\(\s*(['"]?)([^'")]+)\1\s*\)/gi)]
  .map((m) => m[2].trim())
  .filter((u) => !/^(?:data:|#)/i.test(u));
if (cssUrls.length) fail(`the stylesheet references external files: ${cssUrls.join(', ')}.`);

// Inside <script>, the HTML tokenizer ends the element at "</script", and "<!--" followed by
// "<script" switches to the double-escaped state where the real closing tag is ignored.
// Rewrite every "<" that starts one of those sequences as \x3C: that is the same character in
// string, template and regex literals, and harmless in comments. In bare code it would be a
// syntax error, so the result is re-parsed below and the build fails instead of shipping it.
const escapedScript = script.replace(/<(?=\/?script|!--)/gi, '\\x3C');
if (escapedScript !== script) {
  try {
    parseAst(escapedScript, { sourceType: 'module' });
  } catch (err) {
    fail(`escaping "<script", "</script" or "<!--" in ${scriptPath} broke its syntax (${err.message}).`);
  }
}
const escapedStyle = style.replace(/<(?=\/style)/gi, '\\3C ');
if (/<\/script|<!--|<script/i.test(escapedScript) || /<\/style/i.test(escapedStyle)) fail('unsafe sequences remain after escaping.');

// Function replacers so "$&" and friends in the bundle are not treated as patterns.
const standalone = html
  .replace(scriptTag, () => `<script type="module">${escapedScript}</script>`)
  .replace(styleTag, () => `<style>${escapedStyle}</style>`);

// Sanity check: inlining must not change how many script elements open and close.
const count = (s, re) => (s.match(re) || []).length;
const opens = count(standalone, /<script\b/gi);
const closes = count(standalone, /<\/script\b/gi);
if (opens !== count(html, /<script\b/gi) || closes !== count(html, /<\/script\b/gi)) {
  fail(`inlining changed the script structure (${opens} openings, ${closes} closings).`);
}

await writeFile(out, BANNER + standalone);
const kb = (Buffer.byteLength(BANNER + standalone) / 1024).toFixed(0);
console.log(`standalone: wrote portal-panic.html (${kb} KB; inlined ${scriptPath} and ${stylePath}).`);
